export type Translations = typeof strings.en;

// Dynamic t() — checks hardcoded strings first, then localStorage cache
import { getUITranslation } from "../lib/langConfig";

export function t(lang: string, key: TranslationKey): string {
  // Hardcoded languages
  if (lang === "en" || lang === "es" || lang === "pl") {
    return strings[lang as Lang][key] ?? strings.en[key] ?? key;
  }
  // Dynamic languages — check cached translations
  const cached = getUITranslation(lang, key);
  if (cached) return cached;
  // Fallback to English
  return strings.en[key] ?? key;
}

// Format a qty + unit pair for display, with a space between them and a
// language-specific abbreviation for "pcs"/"pack". Weight/volume units (kg, g,
// L, ml, cl) are universal and rendered as-is.
export function formatQtyUnit(
  qty: string | null | undefined,
  unit: string | null | undefined,
  lang: string,
): string {
  if (!qty) return "";
  if (!unit) return qty;
  const u = unit.toLowerCase();
  let label = unit;
  if (u === "x") label = t(lang, "unitPcs");
  else if (u === "pack" || u === "packs") label = t(lang, "unitPack");
  return `${qty} ${label}`;
}
